interface ButtonProps extends ButtonPrimitive.Props, VariantProps<typeof buttonVariants> {
  loading?: boolean
  loaderLeft?: boolean 
  loaderRight?: boolean
}

function Button({
  className,
  variant = "primary",
  size = "primary",
  loading = false,

  children,
  disabled,
  ...props
}: ButtonProps) {
  const local=useLocale();
  const isArabic=local==='ar';
  const isEnglish=local==='en';
  return (
    <ButtonPrimitive
      data-slot="button"
      disabled={loading || disabled}
      aria-busy={loading}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    >
      {loading ? (
        <>
          {children}
          <span className="mb-1" data-icon="inline-start mb-1" aria-hidden="true">{<Loader2 className="animate-spin " aria-hidden="true" />}</span>
        </>
      ) : (
        <>
            {children}
        </>
      )
      }

    </ButtonPrimitive>
  )
}

